import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile, readdir } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { CodexAdapter } from '../lib/codex-adapter.mjs';
import { Orchestrator } from '../lib/engine.mjs';
import { createControlRoom } from '../server.mjs';

const args = process.argv.slice(2);
if (!args.includes('--confirm-live-model-turns')) throw new Error('Explicit --confirm-live-model-turns is required. This uses your Codex allowance.');
if (!process.env.CHRONOS_TEST_DEPS) throw new Error('Set CHRONOS_TEST_DEPS to a local Playwright node_modules directory.');
const get = (name) => args.includes(name) ? args[args.indexOf(name) + 1] : undefined;
const output = resolve(get('--output') || join('dist', 'control-room-live-browser-' + Date.now()));
const workspace = join(output, 'workspace');
await mkdir(workspace, { recursive: true });
const marker = 'CHRONOS_UI_' + randomBytes(6).toString('hex');
await writeFile(join(workspace, 'fixture.txt'), marker + '\n', { flag: 'wx' });
const adapter = new CodexAdapter({ codexPath: get('--codex'), cwd: workspace });
const engine = await new Orchestrator({ adapter, statePath: join(output, 'queue.json') }).initialize();
let room, browser;
try {
  room = await createControlRoom({ engine });
  const { chromium } = await import(pathToFileURL(join(process.env.CHRONOS_TEST_DEPS, 'playwright/index.mjs')).href);
  browser = await chromium.launch({ headless: true, ...(process.env.CHRONOS_BROWSER_CHANNEL ? { channel: process.env.CHRONOS_BROWSER_CHANNEL } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(room.url);
  await page.waitForSelector('.workflow-select');
  await page.getByLabel('Create from template').selectOption('blank');
  await page.getByRole('button', { name: 'Add stage', exact: true }).click();
  await page.getByLabel('Stage name', { exact: true }).fill('Read the local fixture');
  await page.getByLabel('Assignment', { exact: true }).fill('Use the shell to read fixture.txt in the current workspace. Return exactly its contents. Do not inspect other directories.');
  await page.getByLabel('Output routing').selectOption('approval');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.save-state')?.textContent === 'Saved');
  await page.getByRole('button', { name: 'Add work item', exact: true }).click();
  await page.locator('#packet-title').fill('Read the local fixture');
  await page.locator('#packet-input').fill('Read only the local fixture and report its marker.');
  await page.getByRole('button', { name: 'Queue work item', exact: true }).click();
  await page.getByRole('button', { name: 'Connect', exact: true }).click();
  await page.getByRole('button', { name: 'Disconnect', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Permissions', exact: true }).click();
  await page.getByRole('button', { name: 'Authorize session', exact: true }).click();
  await page.getByRole('button', { name: 'Run', exact: true }).click();
  await page.waitForFunction(() => !!document.querySelector('.task-detail .status-review'), undefined, { timeout: 180000 });
  assert.match(await page.locator('.task-detail .result').first().textContent(), new RegExp(marker));
  assert.equal(adapter.effectivePolicy.sandbox, 'readOnly');
  assert.equal(adapter.effectivePolicy.approvalPolicy, 'never');
  await page.screenshot({ path: join(output, 'desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Accept output', exact: true }).click();
  await page.waitForFunction(() => !!document.querySelector('.task-detail .status-accepted'));
  const workflowId = engine.snapshot().packets[0].workflowId;
  await page.reload();
  await page.getByLabel('Selected workflow').selectOption(workflowId);
  await page.getByRole('button', { name: 'Queues', exact: false }).click();
  await page.locator('.task-row').first().click();
  await page.waitForFunction(() => !!document.querySelector('.task-detail .status-accepted'));
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: join(output, 'mobile.png'), fullPage: true });
  page.once('dialog', (dialog) => dialog.accept());
  await page.getByRole('button', { name: 'Stop Control Room', exact: true }).click();
  await page.getByText('Control Room stopped', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  assert.equal(await readFile(join(workspace, 'fixture.txt'), 'utf8'), marker + '\n');
  assert.deepEqual(await readdir(workspace), ['fixture.txt']);
  const report = { result: 'PASS', protocol: 'real_codex_app_server', modelTurnsRequested: 1, browser: 'Chromium', execution: 'real_shell_read', acceptance: true, authenticatedReload: true, shutdown: true, mobileOverflow: false, workspaceUnchanged: true };
  await writeFile(join(output, 'report.json'), JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report));
} finally { if (browser) await browser.close(); if (room) await room.close(); else await engine.close(); }
